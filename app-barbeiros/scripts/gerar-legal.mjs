// Generates src/features/legal/documentos.gerado.ts from legal/*.md, so the
// app shows exactly the text that goes to legal review and to the website.
// Run after editing the .md files: npm run legal
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const ler = (f) => readFileSync(join(root, 'legal', f), 'utf8');
const saida = `// Generated by scripts/gerar-legal.mjs from legal/*.md. Do not edit by hand.
export const DOCUMENTOS = {
  termos: ${JSON.stringify(ler('termos-de-uso.md'))},
  privacidade: ${JSON.stringify(ler('politica-de-privacidade.md'))},
} as const;

export type Documento = keyof typeof DOCUMENTOS;
`;
writeFileSync(join(root, 'src', 'features', 'legal', 'documentos.gerado.ts'), saida);
console.log('ok · src/features/legal/documentos.gerado.ts');
